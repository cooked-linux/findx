//! Full-text search (FTS5) queries, document indexing, and ranking.

use rusqlite::{Connection, params};

use crate::errors::DbError;

/// Document payload to index into the FTS5 virtual table.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct FtsDocument {
    /// Absolute filesystem path.
    pub path: String,
    /// Basename of the file.
    pub filename: String,
    /// Extracted text content or body.
    pub content: String,
    /// MIME type string (e.g. `text/plain`, `application/pdf`).
    pub mime_type: String,
    /// Associated space- or comma-separated tags.
    pub tags: String,
}

impl FtsDocument {
    /// Creates a new FTS document.
    #[must_use]
    pub fn new(
        path: impl Into<String>,
        filename: impl Into<String>,
        content: impl Into<String>,
        mime_type: impl Into<String>,
        tags: impl Into<String>,
    ) -> Self {
        Self {
            path: path.into(),
            filename: filename.into(),
            content: content.into(),
            mime_type: mime_type.into(),
            tags: tags.into(),
        }
    }
}

/// A matched result from an FTS5 search query.
#[derive(Debug, Clone, PartialEq)]
pub struct FtsSearchResult {
    /// Absolute filesystem path of the matched document.
    pub path: String,
    /// Filename of the matched document.
    pub filename: String,
    /// MIME type.
    pub mime_type: String,
    /// Associated tags.
    pub tags: String,
    /// BM25 ranking score computed by SQLite FTS5 (lower/more negative indicates better relevance).
    pub rank: f64,
    /// Highlighted excerpt snippet generated by FTS5.
    pub snippet: String,
}

/// Sanitizes user queries for FTS5 matching, stripping syntax characters and appending wildcards.
#[must_use]
pub fn sanitize_query(raw: &str, prefix: bool) -> String {
    let tokens: Vec<String> = raw
        .split_whitespace()
        .map(|word| {
            let has_star = word.ends_with('*');
            let clean: String = word
                .chars()
                .filter(|c| c.is_alphanumeric() || *c == '_' || *c == '-')
                .collect();
            let trimmed = clean.trim_matches('-').trim_matches('_').to_string();
            if trimmed.is_empty() {
                String::new()
            } else if prefix || has_star {
                format!("{trimmed}*")
            } else {
                trimmed
            }
        })
        .filter(|token| !token.is_empty())
        .collect();

    tokens.join(" ")
}

/// Builder for constructing and executing parameterized FTS5 search queries.
#[derive(Debug, Clone)]
pub struct FtsQueryBuilder {
    raw_query: String,
    prefix: bool,
    limit: usize,
    offset: usize,
    mime_type: Option<String>,
    snippet_column: i32,
    start_tag: String,
    end_tag: String,
    ellipsis: String,
    max_tokens: usize,
}

impl FtsQueryBuilder {
    /// Constructs a query builder with sensible defaults.
    #[must_use]
    pub fn new(query: impl Into<String>) -> Self {
        Self {
            raw_query: query.into(),
            prefix: false,
            limit: 50,
            offset: 0,
            mime_type: None,
            snippet_column: -1,
            start_tag: "<b>".to_string(),
            end_tag: "</b>".to_string(),
            ellipsis: "...".to_string(),
            max_tokens: 12,
        }
    }

    /// Enables or disables automatic prefix matching (`*`) on each search term.
    #[must_use]
    pub const fn prefix(mut self, enabled: bool) -> Self {
        self.prefix = enabled;
        self
    }

    /// Sets the maximum number of results to return.
    #[must_use]
    pub const fn limit(mut self, limit: usize) -> Self {
        self.limit = limit;
        self
    }

    /// Sets the pagination offset.
    #[must_use]
    pub const fn offset(mut self, offset: usize) -> Self {
        self.offset = offset;
        self
    }

    /// Restricts results to a specific MIME type.
    #[must_use]
    pub fn mime_type(mut self, mime_type: impl Into<String>) -> Self {
        self.mime_type = Some(mime_type.into());
        self
    }

    /// Configures snippet generation parameters.
    ///
    /// `column_index`: -1 to select best match column, or 2 for `content`.
    #[must_use]
    pub fn snippet_config(
        mut self,
        column_index: i32,
        start_tag: impl Into<String>,
        end_tag: impl Into<String>,
        ellipsis: impl Into<String>,
        max_tokens: usize,
    ) -> Self {
        self.snippet_column = column_index;
        self.start_tag = start_tag.into();
        self.end_tag = end_tag.into();
        self.ellipsis = ellipsis.into();
        self.max_tokens = max_tokens;
        self
    }

    /// Executes the parameterized FTS5 query against the database.
    ///
    /// # Errors
    ///
    /// Returns a [`DbError`] if SQLite query execution fails.
    pub fn execute(&self, conn: &Connection) -> Result<Vec<FtsSearchResult>, DbError> {
        let sanitized = sanitize_query(&self.raw_query, self.prefix);
        if sanitized.is_empty() {
            return Ok(Vec::new());
        }

        let limit = i64::try_from(self.limit).unwrap_or(i64::MAX);
        let offset = i64::try_from(self.offset).unwrap_or(0);
        let max_tokens = i64::try_from(self.max_tokens).unwrap_or(12);

        let mut results = Vec::new();

        if let Some(ref mime) = self.mime_type {
            let sql = "\
SELECT path, filename, mime_type, tags,
       bm25(files_fts) AS rank,
       snippet(files_fts, ?1, ?2, ?3, ?4, ?5) AS snippet_text
FROM files_fts
WHERE files_fts MATCH ?6 AND mime_type = ?7
ORDER BY rank ASC
LIMIT ?8 OFFSET ?9;";

            let mut stmt = conn.prepare(sql)?;
            let rows = stmt.query_map(
                params![
                    self.snippet_column,
                    self.start_tag,
                    self.end_tag,
                    self.ellipsis,
                    max_tokens,
                    sanitized,
                    mime,
                    limit,
                    offset,
                ],
                |row| {
                    Ok(FtsSearchResult {
                        path: row.get(0)?,
                        filename: row.get(1)?,
                        mime_type: row.get(2)?,
                        tags: row.get(3)?,
                        rank: row.get(4)?,
                        snippet: row.get(5)?,
                    })
                },
            )?;

            for row in rows {
                results.push(row?);
            }
        } else {
            let sql = "\
SELECT path, filename, mime_type, tags,
       bm25(files_fts) AS rank,
       snippet(files_fts, ?1, ?2, ?3, ?4, ?5) AS snippet_text
FROM files_fts
WHERE files_fts MATCH ?6
ORDER BY rank ASC
LIMIT ?7 OFFSET ?8;";

            let mut stmt = conn.prepare(sql)?;
            let rows = stmt.query_map(
                params![
                    self.snippet_column,
                    self.start_tag,
                    self.end_tag,
                    self.ellipsis,
                    max_tokens,
                    sanitized,
                    limit,
                    offset,
                ],
                |row| {
                    Ok(FtsSearchResult {
                        path: row.get(0)?,
                        filename: row.get(1)?,
                        mime_type: row.get(2)?,
                        tags: row.get(3)?,
                        rank: row.get(4)?,
                        snippet: row.get(5)?,
                    })
                },
            )?;

            for row in rows {
                results.push(row?);
            }
        }

        Ok(results)
    }
}

/// Indexes or updates a document in the `files_fts` virtual table.
///
/// If a document with `doc.path` already exists, it is replaced.
///
/// # Errors
///
/// Returns a [`DbError`] if SQLite statements fail.
pub fn index_document(conn: &Connection, doc: &FtsDocument) -> Result<(), DbError> {
    delete_document(conn, &doc.path)?;
    conn.execute(
        "INSERT INTO files_fts (path, filename, content, mime_type, tags) VALUES (?1, ?2, ?3, ?4, ?5);",
        params![doc.path, doc.filename, doc.content, doc.mime_type, doc.tags],
    )?;
    Ok(())
}

/// Deletes a document from the `files_fts` table by path.
///
/// # Errors
///
/// Returns a [`DbError`] if SQLite execution fails.
pub fn delete_document(conn: &Connection, path: &str) -> Result<usize, DbError> {
    let affected = conn.execute("DELETE FROM files_fts WHERE path = ?1;", params![path])?;
    Ok(affected)
}

/// Returns the total count of documents currently indexed in `files_fts`.
///
/// # Errors
///
/// Returns a [`DbError`] if SQLite query fails.
pub fn count_documents(conn: &Connection) -> Result<usize, DbError> {
    let count: i64 = conn.query_row("SELECT COUNT(1) FROM files_fts;", [], |row| row.get(0))?;
    Ok(usize::try_from(count).unwrap_or(0))
}

/// Convenience function executing an FTS search with prefix matching and a limit.
///
/// # Errors
///
/// Returns a [`DbError`] if query execution fails.
pub fn search(
    conn: &Connection,
    query: &str,
    limit: usize,
) -> Result<Vec<FtsSearchResult>, DbError> {
    FtsQueryBuilder::new(query)
        .prefix(true)
        .limit(limit)
        .execute(conn)
}

#[cfg(test)]
#[allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    clippy::assert_is_empty
)]
mod tests {
    use super::*;
    use crate::db::migrations::apply_migrations;

    fn setup_fts_db() -> Connection {
        let mut conn = Connection::open_in_memory().expect("open in memory");
        apply_migrations(&mut conn).expect("apply migrations");
        conn
    }

    #[test]
    fn test_fts_index_and_search() {
        let conn = setup_fts_db();

        let doc1 = FtsDocument::new(
            "/home/user/docs/report.pdf",
            "report.pdf",
            "This is the quarterly financial report containing revenue and growth metrics.",
            "application/pdf",
            "finance,work",
        );
        let doc2 = FtsDocument::new(
            "/home/user/notes/todo.txt",
            "todo.txt",
            "Remember to buy milk and schedule quarterly dental cleaning.",
            "text/plain",
            "personal",
        );

        index_document(&conn, &doc1).expect("index doc1");
        index_document(&conn, &doc2).expect("index doc2");

        assert_eq!(count_documents(&conn).expect("count"), 2);

        // Search for quarterly with prefix
        let results = search(&conn, "quarterly", 10).expect("search");
        assert_eq!(results.len(), 2);

        // Doc1 should rank higher for "financial"
        let fin_results = search(&conn, "financial", 10).expect("search financial");
        assert_eq!(fin_results.len(), 1);
        assert_eq!(fin_results[0].path, "/home/user/docs/report.pdf");
        assert!(fin_results[0].snippet.contains("financial"));

        // Delete doc1
        let deleted = delete_document(&conn, "/home/user/docs/report.pdf").expect("delete");
        assert_eq!(deleted, 1);
        assert_eq!(count_documents(&conn).expect("count"), 1);

        let fin_after = search(&conn, "financial", 10).expect("search financial after delete");
        assert!(fin_after.is_empty());
    }

    #[test]
    fn test_fts_mime_filter_and_snippets() {
        let conn = setup_fts_db();

        let doc1 = FtsDocument::new(
            "/code/main.rs",
            "main.rs",
            "fn main() { println!(\"Hello rust world\"); }",
            "text/rust",
            "code",
        );
        let doc2 = FtsDocument::new(
            "/docs/readme.md",
            "readme.md",
            "Rust is a systems programming language focused on safety and speed.",
            "text/markdown",
            "doc",
        );

        index_document(&conn, &doc1).expect("index doc1");
        index_document(&conn, &doc2).expect("index doc2");

        // Filter by text/rust
        let rust_results = FtsQueryBuilder::new("rust")
            .mime_type("text/rust")
            .execute(&conn)
            .expect("query rust");
        assert_eq!(rust_results.len(), 1);
        assert_eq!(rust_results[0].filename, "main.rs");

        // Custom snippet tags
        let snippet_results = FtsQueryBuilder::new("safety")
            .snippet_config(-1, "<highlight>", "</highlight>", "...", 10)
            .execute(&conn)
            .expect("query safety");
        assert_eq!(snippet_results.len(), 1);
        assert!(
            snippet_results[0]
                .snippet
                .contains("<highlight>safety</highlight>")
        );
    }

    #[test]
    fn test_fts_query_sanitization() {
        assert_eq!(sanitize_query("hello world", false), "hello world");
        assert_eq!(sanitize_query("hello world", true), "hello* world*");
        assert_eq!(sanitize_query("file* test", false), "file* test");
        assert_eq!(
            sanitize_query("malicious'; DROP TABLE--", false),
            "malicious DROP TABLE"
        );
        assert_eq!(sanitize_query("   ", false), "");
    }
}
